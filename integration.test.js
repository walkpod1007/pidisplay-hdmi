const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path'),{spawn}=require('node:child_process');
test('HTTP auth, cross-origin protection, removed music integration and demo safeguards',async(t)=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'pidisplay-test-'));
 const proc=spawn(process.execPath,['server.js'],{cwd:__dirname,env:{...process.env,PIDISPLAY_STATE:dir,PIDISPLAY_DEMO:'1',PIDISPLAY_BIND:'127.0.0.1',PORT:'18787'},stdio:'pipe'});
 t.after(()=>proc.kill());
 await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('startup timeout')),8000);proc.stdout.once('data',()=>{clearTimeout(timer);resolve();});proc.once('exit',()=>{clearTimeout(timer);reject(Error('server exited'));});});
 const base='http://127.0.0.1:18787';
 const post=(p,d,c='',origin=base)=>fetch(base+p,{method:'POST',headers:{'Content-Type':'application/json',Cookie:c,Origin:origin},body:JSON.stringify(d)});
 assert.equal((await fetch(base+'/api/settings')).status,401);
 const badHost=await new Promise((resolve,reject)=>{require('node:http').get(base+'/api/local-setup',{headers:{host:'attacker.example'}},r=>{r.resume();resolve(r.statusCode);}).on('error',reject);});
 assert.equal(badHost,403);
 assert.equal((await post('/api/login',{pin:'wrong'})).status,401);
 const pin=JSON.parse(fs.readFileSync(path.join(dir,'settings.json'))).pin;
 assert.equal((await post('/api/login',{pin},'','https://evil.example')).status,403);
 const login=await post('/api/login',{pin});assert.equal(login.status,200);const cookie=login.headers.get('set-cookie').split(';')[0];
 assert.match(login.headers.get('set-cookie'),/HttpOnly/);
 assert.equal((await post('/api/settings',{source:'bogus',zone:''},cookie)).status,400);
 assert.equal((await post('/api/settings',{source:'sonos',zone:'',sonosGroup:'room-1'},cookie)).status,200);
 const saved=await(await fetch(base+'/api/settings',{headers:{Cookie:cookie}})).json();assert.equal(saved.sonosGroup,'room-1');assert.equal(saved.source,'sonos');
 assert.equal((await(await fetch(base+'/api/status')).json()).phase,'ready');
 const setup=await(await fetch(base+'/api/local-setup')).json();assert.match(setup.qr,/^data:image\/png;base64,/);
 assert.equal((await post('/api/setup/skip',{})).status,401);
 assert.equal((await post('/api/wifi',{ssid:'home',password:'testpassword'},cookie)).status,409);
 const status=await(await fetch(base+'/api/status')).json();assert(!('pin'in status));assert(!JSON.stringify(status).includes(pin));
 assert.equal((await post('/api/spotify/start',{},cookie)).status,404);
 assert.equal((await post('/api/settings',{source:'spotify',zone:''},cookie)).status,400);
 assert(!('spotifyQR' in setup));
 assert(!/spotify/i.test(await(await fetch(base+'/setup')).text()));
 assert.equal((await fetch(base+'/setup')).status,200);
 assert.equal((await fetch(base+'/')).status,200);
});
